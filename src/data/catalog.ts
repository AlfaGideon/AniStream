export const byId = (id: string): TitleItem | undefined => TITLES.find((x) => x.id === id);

export const franchiseTitles = (franchise: string): TitleItem[] =>
  TITLES.filter((x) => x.franchise === franchise);

export const ALL_GENRES = Array.from(new Set(TITLES.flatMap((x) => x.genres))).sort((a, b) =>
  a.localeCompare(b, 'ru'),
);

const EP_NAMES = [
  'Пролог', 'Встреча', 'Испытание', 'Клятва', 'Тени прошлого', 'Перелом',
  'Восхождение', 'Разлом', 'Тихая гавань', 'Буря', 'Откровение', 'Финал арки',
];

/** Генерирует список серий для аниме (демо-источник видео). */
export function episodesFor(item: TitleItem): Episode[] {
  const count = Math.min(item.episodesCount ?? 0, 12); // в каталоге показываем первые серии
  return Array.from({ length: count }, (_, i) => ({
    num: i + 1,
    name: `${i + 1}. ${EP_NAMES[i % EP_NAMES.length]}`,
    durationMin: 23 + ((i * 7) % 4),
    src: SAMPLE_VIDEOS[i % SAMPLE_VIDEOS.length],
  }));
}

